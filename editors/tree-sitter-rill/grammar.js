const commaSep1 = rule => seq(rule, repeat(seq(',', rule)));
const commaSep = rule => optional(commaSep1(rule));

module.exports = grammar({
  name: 'rill',
  extras: $ => [/\s/, $.comment],
  word: $ => $.identifier,
  conflicts: $ => [[$._primary, $._call_name], [$._argument_primary, $._call_name], [$.field_expression, $._call_name]],
  reserved: {global: _ => [
    'let', 'mut', 'move', 'inout', 'read', 'record', 'extern', 'const', 'fn', 'type',
    'match', 'while', 'do', 'in', 'if', 'then', 'else', 'true', 'false', 'not',
  ]},
  rules: {
    source_file: $ => seq(
      repeat(choice($.import_declaration, $.native_directive)),
      repeat($._declaration),
    ),
    _declaration: $ => choice(
      $.function_declaration, $.legacy_function_declaration,
      $.type_declaration, $.extern_function_declaration, $.extern_constant_declaration,
    ),
    import_declaration: $ => seq('import', field('module', $.qualified_identifier), optional(seq('as', field('alias', $.identifier))), ';'),
    native_directive: $ => seq('@', field('name', choice('include', 'link', 'pkg_config')), '(', $.string, ')', ';'),
    function_declaration: $ => seq(optional('export'), 'fn', field('name', $.identifier), field('parameters', $.parameters), optional(seq('->', field('result', $.type_expression))), field('body', $.block), optional(';')),
    parameters: $ => seq('(', optional(seq(commaSep1($.parameter), optional(','))), ')'),
    parameter: $ => seq(optional(field('mode', choice('read', 'inout'))), field('name', $.identifier), optional(seq(':', field('type', $.type_expression)))),
    legacy_function_declaration: $ => seq(optional('export'), 'let', field('name', $.identifier), repeat($.legacy_parameter), '=', field('body', $._expression), optional(';')),
    legacy_parameter: $ => choice(
      field('name', $.identifier),
      seq('(', choice(
        seq(field('mode', choice('read', 'inout')), field('name', $.identifier), optional(seq(':', field('type', $.type_expression)))),
        seq(field('name', $.identifier), ':', field('type', $.type_expression)),
      ), ')'),
    ),
    type_declaration: $ => seq(optional('export'), 'type', field('name', $.type_identifier), optional($.type_parameters), '=', choice($.record_type, $.variant_list), optional(';')),
    type_parameters: $ => seq('<', commaSep1($.type_identifier), '>'),
    record_type: $ => seq('{', optional(seq($.field_declaration, repeat(seq(';', $.field_declaration)), optional(';'))), '}'),
    field_declaration: $ => seq(field('name', $.identifier), ':', field('type', $.type_expression)),
    variant_list: $ => seq(optional('|'), $.variant, repeat(seq('|', $.variant))),
    variant: $ => seq(field('name', $.identifier), optional(seq('(', commaSep($.type_expression), ')'))),
    type_expression: $ => seq(field('name', $.type_identifier), repeat(seq('.', $.type_identifier)), optional(seq('<', commaSep1($.type_expression), '>'))),
    type_identifier: $ => $.identifier,
    extern_function_declaration: $ => seq(optional('export'), 'extern', 'fn', field('name', $.identifier), '(', commaSep($.extern_parameter), ')', '->', field('result', $.foreign_type), ';'),
    extern_parameter: $ => seq(field('name', $.identifier), ':', field('type', $.foreign_type)),
    extern_constant_declaration: $ => seq(optional('export'), 'extern', 'const', field('name', $.identifier), ':', field('type', $.foreign_type), ';'),
    foreign_type: $ => choice('i32', 'u8', 'u32', 'u64', 'f32', 'bool', 'unit', 'cstr', seq(choice('ptr', 'const_ptr'), '<', $.type_identifier, '>')),
    block: $ => seq('{', repeat(choice($.local_binding, $.expression_statement)), optional($._block_expression), '}'),
    local_binding: $ => seq('let', optional('mut'), field('name', $.identifier), '=', field('value', $._expression), ';'),
    expression_statement: $ => seq($._block_expression, ';'),
    _expression: $ => choice($.let_expression, $._block_expression),
    _block_expression: $ => choice($.if_expression, $.while_expression, $.match_expression, $.assignment_expression, $._binary_expression),
    let_expression: $ => prec.right(-2, seq('let', optional('mut'), field('name', $.identifier), '=', field('value', $._expression), 'in', field('body', $._expression))),
    if_expression: $ => prec.right(-1, seq('if', field('condition', $._expression), choice(
      seq(field('consequence', $.block), optional(seq('else', field('alternative', $.block)))),
      seq('then', field('consequence', $._expression), 'else', field('alternative', $._expression)),
    ))),
    while_expression: $ => prec.right(-1, seq('while', field('condition', $._expression), choice(field('body', $.block), seq('do', field('body', $._expression))))),
    match_expression: $ => prec.right(-1, seq('match', field('value', $._expression), '{', optional('|'), $.match_arm, repeat(seq('|', $.match_arm)), '}')),
    match_arm: $ => seq(field('pattern', $._pattern), '=>', field('body', $._expression)),
    _pattern: $ => choice($.identifier, $.constructor_pattern, $.qualified_pattern, $.integer, $.negative_pattern, $.boolean, $.unit, $.parenthesized_pattern),
    constructor_pattern: $ => seq(field('name', $.qualified_identifier), '(', commaSep($._pattern), ')'),
    qualified_pattern: $ => seq($.identifier, repeat1(seq('.', $.identifier))),
    negative_pattern: $ => seq('-', $.integer),
    parenthesized_pattern: $ => seq('(', $._pattern, ')'),
    assignment_expression: $ => prec.right(0, seq(field('left', choice($.identifier, $.field_expression)), '<-', field('right', $._expression))),
    _binary_expression: $ => choice($._atom, $.application_expression, $.binary_expression, $.function_operator_expression),
    function_operator_expression: $ => choice(
      prec.left(1, seq(field('left', $._binary_expression), field('operator', '|>'), field('right', $._binary_expression))),
      prec.right(1, seq(field('left', $._binary_expression), field('operator', '<|'), field('right', $._binary_expression))),
      ...['>>', '<<'].map(operator => prec.left(4, seq(field('left', $._binary_expression), field('operator', operator), field('right', $._binary_expression)))),
    ),
    binary_expression: $ => choice(...[
      [2, '||'], [3, '&&'], [5, '=='], [5, '!='], [6, '<'], [6, '<='], [6, '>'], [6, '>='], [7, '+'], [7, '-'], [8, '*'], [8, '/'], [8, '%'],
    ].map(([precedence, operator]) => prec.left(precedence, seq(field('left', $._binary_expression), field('operator', operator), field('right', $._binary_expression))))),
    _atom: $ => choice($._primary, $.call_expression, $.apply_expression, $.unary_expression),
    _primary: $ => choice($.integer, $.boolean, $.string, $.c_string, $.identifier, $.field_expression, $.lambda_expression, $.move_expression, $.record_expression, $.unit, $.parenthesized_expression, $.block),
    unary_expression: $ => prec(10, seq(field('operator', choice('-', 'not', '!')), field('operand', $._atom))),
    lambda_expression: $ => seq('fn', field('parameters', $.parameters), field('body', $.block)),
    move_expression: $ => seq('move', $.identifier),
    record_expression: $ => seq('record', field('type', $.qualified_identifier), '{', optional(seq($.record_field, repeat(seq(';', $.record_field)), optional(';'))), '}'),
    record_field: $ => seq(field('name', $.identifier), '=', field('value', $._expression)),
    parenthesized_expression: $ => seq('(', $._expression, ')'),
    unit: _ => seq('(', ')'),
    call_expression: $ => prec(12, seq(field('function', alias($._call_name, $.qualified_identifier)), field('arguments', $.arguments))),
    apply_expression: $ => prec.left(11, seq(field('function', $._atom), field('arguments', $.arguments))),
    application_expression: $ => prec.left(9, seq(field('function', $._atom), repeat1(field('argument', $._argument_atom)))),
    // The first call accepts whitespace, including legacy f (x). Argument
    // postfix calls require adjacency: f x(y) and f x (y) have different trees.
    _argument_atom: $ => choice(
      $._argument_primary,
      alias($._argument_call_expression, $.call_expression),
      alias($._argument_apply_expression, $.apply_expression),
    ),
    _argument_primary: $ => choice($.integer, $.boolean, $.string, $.c_string, $.identifier, $.field_expression, $.lambda_expression, $.move_expression, $.record_expression, $.unit, $.parenthesized_expression),
    _argument_call_expression: $ => prec(12, seq(field('function', alias($._call_name, $.qualified_identifier)), field('arguments', alias($._adjacent_arguments, $.arguments)))),
    _argument_apply_expression: $ => prec.left(11, seq(field('function', $._argument_atom), field('arguments', alias($._adjacent_arguments, $.arguments)))),
    _call_name: $ => seq($.identifier, optional(seq('.', $.identifier))),
    // Both tokens keep root postfix calls available when the adjacent token
    // is also valid in a competing whitespace-argument parse.
    arguments: $ => prec(1, seq(choice('(', token.immediate('(')), commaSep(choice($._expression, $.inout_argument)), ')')),
    _adjacent_arguments: $ => prec(1, seq(token.immediate('('), commaSep(choice($._expression, $.inout_argument)), ')')),
    inout_argument: $ => seq('inout', choice($.identifier, $.field_expression)),
    qualified_identifier: $ => seq($.identifier, repeat(seq('.', $.identifier))),
    field_expression: $ => prec(12, seq(field('root', $.identifier), repeat1(seq('.', field('field', $.identifier))))),
    boolean: _ => choice('true', 'false'),
    integer: _ => /[0-9]+/,
    string: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    c_string: $ => seq('c"', repeat(choice($.c_string_content, $.c_escape_sequence)), '"'),
    string_content: _ => token.immediate(choice(/[^"\\\r\n\x00]+/, "\0")),
    c_string_content: _ => token.immediate(/[^"\\\r\n\x00]+/),
    c_escape_sequence: _ => token.immediate(/\\[nrt\\"]/),
    escape_sequence: _ => token.immediate(/\\[nrt0\\"]/),
    identifier: _ => /[A-Za-z_][A-Za-z0-9_]*/,
    comment: _ => token(seq('//', /[^\n]*/)),
  },
});
